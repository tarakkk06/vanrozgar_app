import '../models/village.dart';
import '../models/resource.dart';
import '../models/livelihood_idea.dart';
import '../models/gram_sabha_record.dart';
import 'livelihood_engine.dart';
import 'resource_scoring_service.dart';

class GramSabhaSummaryReport {
  final String villageName;
  final String taluka;
  final String district;
  final double cfrAreaHa;
  final int householdCount;
  final String dateGenerated;
  final Map<ResourceUtilityLabel, int> resourceCounts;
  final List<LivelihoodRankResult> topIdeas;
  final GramSabhaDecision decision;
  final String legalDisclaimer;

  GramSabhaSummaryReport({
    required this.villageName,
    required this.taluka,
    required this.district,
    required this.cfrAreaHa,
    required this.householdCount,
    required this.dateGenerated,
    required this.resourceCounts,
    required this.topIdeas,
    required this.decision,
    required this.legalDisclaimer,
  });
}

class PdfReportService {
  final ResourceScoringService _resourceService = ResourceScoringService();
  final LivelihoodEngine _engine = LivelihoodEngine();

  GramSabhaSummaryReport generateReportData({
    required Village village,
    required List<ResourceItem> resources,
    required List<LivelihoodIdea> allIdeas,
    required GramSabhaDecision decision,
  }) {
    var counts = _resourceService.countSummary(resources);
    var top5 = _engine.getTop5Ideas(
      allIdeas: allIdeas,
      villageResources: resources,
      profile: village.profile,
    );

    return GramSabhaSummaryReport(
      villageName: village.name,
      taluka: village.taluka,
      district: village.district,
      cfrAreaHa: village.cfrAreaHectares,
      householdCount: village.householdCount,
      dateGenerated: '${DateTime.now().day}/${DateTime.now().month}/${DateTime.now().year}',
      resourceCounts: counts,
      topIdeas: top5,
      decision: decision,
      legalDisclaimer:
          'DISCLAIMER: This document is an advisory decision-support record generated by VanRozgar 2.0 under FRA Rule 4(1)(f). It is not a statutory deed. The Gram Sabha holds supreme constitutional authority to ratify, modify, or reject any proposal.',
    );
  }

  String formatTextSummary(GramSabhaSummaryReport report) {
    StringBuffer sb = StringBuffer();
    sb.writeln('===============================================================');
    sb.writeln('          VANROZGAR 2.0 - GRAM SABHA LIVELIHOOD SUMMARY         ');
    sb.writeln('         (Under Forest Rights Act 2006 & Rule 4(1)(f))          ');
    sb.writeln('===============================================================');
    sb.writeln('Village: ${report.villageName} | Taluka: ${report.taluka} | District: ${report.district}');
    sb.writeln('Recognised CFR Area: ${report.cfrAreaHa} Hectares | Households: ${report.householdCount}');
    sb.writeln('Date: ${report.dateGenerated}');
    sb.writeln('---------------------------------------------------------------');
    sb.writeln('1. CFR RESOURCE AUDIT SUMMARY:');
    sb.writeln('   • Useful Resources:        ${report.resourceCounts[ResourceUtilityLabel.useful]} assets');
    sb.writeln('   • Partly Useful Resources: ${report.resourceCounts[ResourceUtilityLabel.partlyUseful]} assets (Need field repair/desilting)');
    sb.writeln('   • Not Useful Resources:    ${report.resourceCounts[ResourceUtilityLabel.notUseful]} assets');
    sb.writeln('---------------------------------------------------------------');
    sb.writeln('2. TOP 5 AI-RANKED LIVELIHOOD ENTERPRISES:');
    for (int i = 0; i < report.topIdeas.length; i++) {
      var item = report.topIdeas[i];
      sb.writeln('   #${i + 1} [Score: ${item.fitScore}%] ${item.idea.title}');
      sb.writeln('      • Reason: ${item.oneLineReason}');
      sb.writeln('      • Annual Rev: ${item.idea.annualRevenueRange} | Investment: ₹${item.idea.initialInvestmentLakhs}L');
      sb.writeln('      • Legal Base: ${item.idea.legalBase}');
      sb.writeln('      • Community Interest: ${item.idea.markedInterestCount} households');
    }
    sb.writeln('---------------------------------------------------------------');
    sb.writeln('3. GRAM SABHA DECISION & QUORUM RECORD:');
    sb.writeln('   • Total Voters: ${report.decision.totalEligibleVoters} | Present: ${report.decision.attendeesCount} (Women: ${report.decision.femaleAttendeesCount})');
    sb.writeln('   • Quorum Met (Rule 4(2)): ${report.decision.quorumReached ? "YES (Valid)" : "NO (Quorum Shortage)"}');
    sb.writeln('   • Resolution No: ${report.decision.resolutionNumber}');
    sb.writeln('   • Minutes: ${report.decision.meetingMinutesNotes}');
    sb.writeln('   • Assigned Leaders:');
    report.decision.assignedTeamLeaders.forEach((k, v) {
      sb.writeln('      - $k: $v');
    });
    sb.writeln('---------------------------------------------------------------');
    sb.writeln('Signatures:');
    sb.writeln('${report.decision.signedBySecretary}         ${report.decision.signedBySarpanch}');
    sb.writeln('===============================================================');
    sb.writeln(report.legalDisclaimer);
    return sb.toString();
  }
}
