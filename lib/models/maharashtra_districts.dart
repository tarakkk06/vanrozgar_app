  static MaharashtraDistrict? byName(String name) {
    for (final d in districts) {
      if (d.name.toLowerCase() == name.toLowerCase() || d.marathiName == name)
        return d;
    }
    return null;
  }

  static List<String> get divisionNames {
    return districts.map((d) => d.division).toSet().toList();
  }

  static int get totalCfrTitles =>
      districts.fold(0, (sum, d) => sum + d.totalCfrTitlesApproved);

  static int get totalCfrHectares =>
      districts.fold(0, (sum, d) => sum + d.totalCfrRecognisedHectares);
}
