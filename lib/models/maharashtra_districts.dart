class MaharashtraDistrict {
  final String id;
  final String name;
  final String marathiName;
  final String
      division; // Nagpur, Amravati, Nashik, Pune, Konkan, Chhatrapati Sambhajinagar
  final List<String> talukas;
  final int totalCfrRecognisedHectares;
  final int totalCfrTitlesApproved;
  final int potentialCfrVillagesCount;

  const MaharashtraDistrict({
    required this.id,
    required this.name,
    required this.marathiName,
    required this.division,
    required this.talukas,
    required this.totalCfrRecognisedHectares,
    required this.totalCfrTitlesApproved,
    required this.potentialCfrVillagesCount,
  });
}

